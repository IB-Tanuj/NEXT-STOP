-- Persistent Gemini response cache used by trip summaries and query generation.
-- Run this once in the Supabase SQL editor before deploying the API.

CREATE TABLE IF NOT EXISTS gemini_results (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_type TEXT NOT NULL,
    model TEXT NOT NULL,
    input_prompt TEXT NOT NULL,
    output_result JSONB,
    output_text TEXT,
    metadata JSONB NOT NULL DEFAULT '{}'::jsonb,
    lookup_key TEXT UNIQUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

ALTER TABLE gemini_results DISABLE ROW LEVEL SECURITY;
